@dataclass(frozen=True)
class FormatDescriptor:
    """Metadata for a built-in data format."""

    id: str
    module: str
    cls: str
    aliases: tuple[str, ...] = ()
    text: bool = False
    flat: bool = False
    writable: bool = True
    extra: str | None = None
    magic: tuple[bytes, ...] = ()
    description: str | None = None
    example_args: dict[str, Any] | None = None
    limitations: tuple[str, ...] = ()
    doc_url: str | None = None
    # Extended capability declarations. ``None`` is deliberate: an unknown
    # backend-dependent value is safer than optimistic runtime inference.
    maturity: Literal["stable", "experimental", "partial"] = "stable"
    read_memory: Literal["bounded", "whole_input", "backend_defined", "unknown"] = "unknown"
    write_memory: Literal["bounded", "whole_output", "backend_defined", "unknown"] = "unknown"
    native_bulk_read: bool | None = None
    native_bulk_write: bool | None = None
    totals: bool | None = None
    tables: bool | None = None
    selection: tuple[str, ...] = ()
    codec_support: tuple[str, ...] = ()
    source_constraints: tuple[str, ...] = ()
    # Leading-byte detection metadata. ``magic`` prefixes resolve to the
    # canonical id; ``alias_magic`` maps an alias to its own prefix (e.g.
    # pcapng). ``magic_contains`` requires the peek to also contain the given
    # substring (ZIP-based containers); one match is emitted per prefix x
    # contains pair. ``magic_confidence`` applies to all of them.
    magic_confidence: float = 0.99
    magic_contains: tuple[bytes, ...] = ()
    alias_magic: tuple[tuple[str, bytes], ...] = ()


def _fmt(
    id: str,
    module: str,
    cls: str,
    *,
    aliases: tuple[str, ...] = (),
    text: bool = False,
    flat: bool = False,
    writable: bool = True,
    extra: str | None = None,
    magic: tuple[bytes, ...] = (),
    description: str | None = None,
    example_args: dict[str, Any] | None = None,
    limitations: tuple[str, ...] = (),
    doc_url: str | None = None,
    maturity: Literal["stable", "experimental", "partial"] = "stable",
    read_memory: Literal["bounded", "whole_input", "backend_defined", "unknown"] = "unknown",
    write_memory: Literal["bounded", "whole_output", "backend_defined", "unknown"] = "unknown",
    native_bulk_read: bool | None = None,
    native_bulk_write: bool | None = None,
    totals: bool | None = None,
    tables: bool | None = None,
    selection: tuple[str, ...] = (),
    codec_support: tuple[str, ...] = (),
    source_constraints: tuple[str, ...] = (),
    magic_confidence: float = 0.99,
    magic_contains: tuple[bytes, ...] = (),
    alias_magic: tuple[tuple[str, bytes], ...] = (),
) -> FormatDescriptor:
    return FormatDescriptor(
        id=id,
        module=module,
        cls=cls,
        aliases=aliases,
        text=text,
        flat=flat,
        writable=writable,
        extra=extra,
        magic=magic,
        description=description,
        example_args=example_args,
        limitations=limitations,
        doc_url=doc_url,
        maturity=maturity,
        read_memory=read_memory,
        write_memory=write_memory,
        native_bulk_read=native_bulk_read,
        native_bulk_write=native_bulk_write,
        totals=totals,
        tables=tables,
        selection=selection,
        codec_support=codec_support,
        source_constraints=source_constraints,
        magic_confidence=magic_confidence,
        magic_contains=magic_contains,
        alias_magic=alias_magic,
    )


